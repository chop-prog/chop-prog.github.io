export const LANGS = Object.keys(STRINGS);

export function detectLang(saved, navigatorLangs = []) {
  if (LANGS.includes(saved)) return saved;
  return navigatorLangs.some((l) => /^(ru|uk|be|kk)\b/i.test(l)) ? 'ru' : 'en';
}
